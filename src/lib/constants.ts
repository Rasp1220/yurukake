//
// **このリストは実データ（`?inspect=true`）を見て決めること。想像で足さない。**
//
// 当初は「カテゴリは投稿者が固定の選択肢から選んだ構造化データだから信頼
// できる」という想定で、音楽・ゲーム・ペット・自動車などを一括で入れていた。
// しかし2,868件を点検した結果、この想定はこのデータセットには当てはまらない
// ことが分かった。動画プールの中身は個人の旅行系YouTuberが大半で、投稿者が
// カテゴリを内容と無関係に選んでいるためで、実際に次のような取り違えが
// 起きていた（いずれも中身はスポット紹介）。
